def build_payload() -> list[dict]:
    letters = ["А", "Б", "В", "Г"]
    payload: list[dict] = []
    for question, options, correct in QUESTIONS:
        if len(options) != 4:
            raise ValueError(f"Ожидалось 4 варианта: {question}")
        idx = LETTER_INDEX[correct]
        answers = []
        for i, text in enumerate(options):
            answers.append(
                {
                    "text": f"{letters[i]}. {text}",
                    "is_correct": i == idx,
                }
            )
        payload.append({"question": question, "answers": answers})
    return payload


def main() -> None:
    payload = build_payload()
    assert len(payload) == 155, len(payload)
    for item in payload:
        assert sum(1 for a in item["answers"] if a["is_correct"]) == 1
    out = Path(__file__).resolve().parents[1] / "data" / "questions.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {len(payload)} questions to {out}")


if __name__ == "__main__":
    main()
